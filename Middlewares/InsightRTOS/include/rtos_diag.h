#define RTOS_DIAG_TRACE_BATCH_MAX RTOS_TRACE_BATCH_MAX

/* Commit classes for CONTEXT_SWITCH (ID 12) */
typedef enum {
    RTOS_COMMIT_OTHER = 0,
    RTOS_COMMIT_HIGHER_PREEMPT = 1,
    RTOS_COMMIT_YIELD = 2,
    RTOS_COMMIT_SLICE_ROTATION = 3,
    RTOS_COMMIT_BLOCK_OR_WAKE_OTHER = 4,
    RTOS_COMMIT_EXIT = 5,
    RTOS_COMMIT_IDLE_TRANSITION = 6,
    RTOS_COMMIT_MIXED = 7
} rtos_commit_class_t;

/* Explanations generated by rtos_diag_explain_record / rtos_diag_format_explanation */
typedef enum {
    RTOS_EXPLAIN_NONE = 0,
    RTOS_EXPLAIN_TASK_CREATE = 1,
    RTOS_EXPLAIN_TASK_READY = 2,
    RTOS_EXPLAIN_TASK_BLOCK = 3,
    RTOS_EXPLAIN_SCHED_SELECT = 4,
    RTOS_EXPLAIN_WAIT_COMPLETE = 5,
    RTOS_EXPLAIN_PRIORITY_CHANGE = 6,
    RTOS_EXPLAIN_STOP_REQUEST = 7,
    RTOS_EXPLAIN_TASK_TERMINATED = 8,
    RTOS_EXPLAIN_TASK_RECLAIM = 9,
    RTOS_EXPLAIN_DELAY_EXPIRED = 10,
    RTOS_EXPLAIN_TASK_YIELD = 11,
    RTOS_EXPLAIN_CONTEXT_SWITCH = 12
} rtos_explain_kind_t;

typedef struct {
    uint32_t capacity;
    uint32_t count;
    uint32_t schema_version;
    uint32_t event_set_version;
    uint32_t tick_hz;
    uint64_t oldest_sequence;
    uint64_t next_sequence;
    uint32_t overwritten;
    uint32_t producer_dropped;
    uint32_t status;
} rtos_diag_trace_info_t;

typedef struct {
    uint64_t oldest_sequence;
    uint64_t next_sequence;
    uint32_t count;
    uint32_t copied;
    uint32_t overwritten;
    uint32_t producer_dropped;
    uint32_t status;
} rtos_diag_trace_batch_t;

typedef struct {
    rtos_explain_kind_t kind;
    uint16_t primary_slot;
    uint32_t primary_generation;
    bool primary_stale;
    uint16_t related_slot;
    uint32_t related_generation;
    bool related_stale;
    uint8_t previous_priority;
    uint8_t next_priority;
    rtos_commit_class_t commit_class;
    uint32_t reason_flags;
    uint32_t aux_value;
} rtos_diag_explain_t;

