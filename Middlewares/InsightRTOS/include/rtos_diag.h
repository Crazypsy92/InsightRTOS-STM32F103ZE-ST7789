#endif

#ifndef INSIGHT_DIAG_DL
#define INSIGHT_DIAG_DL 0
#endif
#ifndef INSIGHT_DIAG_DEADLOCK
#define INSIGHT_DIAG_DEADLOCK INSIGHT_DIAG_DL
#endif
_Static_assert(INSIGHT_DIAG_DL == 0 || INSIGHT_DIAG_DL == 1, "Diag dl boolean");

#define RTOS_DIAG_DL_NO_OWNER        0xFFFFU
#define RTOS_DIAG_DL_MAX_NODES       8U

#define RTOS_DIAG_DL_FLAG_ANOMALY    (1U << 0)
#define RTOS_DIAG_DL_FLAG_INCOMPLETE (1U << 1)
#define RTOS_DIAG_DL_FLAG_OVERFLOW   (1U << 2)

#define RTOS_DIAG_DL_EDGE_FINITE     (1U << 0)
#define RTOS_DIAG_DL_EDGE_PI_BOOST   (1U << 1)

#define RTOS_DIAG_DL_RES_DEADLOCK    (1U << 0)
#define RTOS_DIAG_DL_RES_HAS_TIMEOUT (1U << 1)
#define RTOS_DIAG_DL_RES_INCOMPLETE  (1U << 2)
#define RTOS_DIAG_DL_RES_ANOMALY     (1U << 3)

typedef struct {
    uint32_t capture_tick;
    uint16_t node_count;
    uint16_t edge_count;
    uint16_t mutex_count;
    uint16_t flags;
    uint8_t captured;
    uint8_t analyzed;
    uint16_t reserved0;
    uint32_t reserved1[2];
} rtos_diag_dl_header_t;
_Static_assert(sizeof(rtos_diag_dl_header_t) == 24U, "DL header 24B");

typedef struct {
    uint16_t slot;
    uint16_t state;
    uint32_t generation;
    uint8_t base_priority;
    uint8_t effective_priority;
    uint16_t owner_slot;
    uint32_t owner_generation;
    uint16_t resource_id;
    uint16_t edge_flags;
    uint32_t wake_tick;
} rtos_diag_dl_node_t;
_Static_assert(sizeof(rtos_diag_dl_node_t) == 24U, "DL node 24B");

typedef struct {
    bool deadlock_detected;
    uint8_t cycle_length;
    uint16_t flags;
    uint32_t capture_tick;
    uint16_t cycle_tasks[8];
    uint16_t cycle_mutexes[8];
    uint32_t earliest_due_tick;
    uint16_t finite_edge_count;
    uint16_t reserved;
} rtos_diag_dl_result_t;
_Static_assert(sizeof(rtos_diag_dl_result_t) == 48U, "DL result 48B");

typedef struct {
    rtos_diag_dl_header_t header;
    rtos_diag_dl_node_t   nodes[8];
#if UINTPTR_MAX == UINT32_MAX
    uint32_t              resource_keys[8];
    uint32_t              task_slots[8];
#else
    uintptr_t             resource_keys[8];
    uint32_t              task_slots[8];
#endif
    uint8_t               scratch[24];
    rtos_diag_dl_result_t result;
    uint8_t               reserved[32];
} rtos_diag_dl_workspace_t;

#if UINTPTR_MAX == UINT32_MAX
_Static_assert(sizeof(rtos_diag_dl_workspace_t) == 384U, "DL workspace 384B budget on 32-bit");
#endif

#if INSIGHT_DIAG_DL
rtos_status_t rtos_diag_dl_capture(rtos_diag_dl_workspace_t *work);
rtos_status_t rtos_diag_dl_analyze(rtos_diag_dl_workspace_t *work);
const rtos_diag_dl_result_t *rtos_diag_dl_result(const rtos_diag_dl_workspace_t *work);
rtos_status_t rtos_diag_dl_verify_current(const rtos_diag_dl_workspace_t *work);
#endif

#endif
